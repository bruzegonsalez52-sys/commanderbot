let currentLang = 'es';

function t(key) {
  return (LANG[currentLang] && LANG[currentLang][key]) || (LANG['es'][key]) || key;
}

function setLang(lang) {
  if (!LANG[lang]) return;
  currentLang = lang;
  localStorage.setItem('commanderbot_lang', lang);
  document.documentElement.lang = lang === 'en' ? 'en' : 'es';
  translatePage();
  if (window.app) window.app.updateExportDisplay();
}

function translatePage() {
  const els = document.querySelectorAll('[data-i18n]');
  els.forEach(el => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  const phs = document.querySelectorAll('[data-i18n-placeholder]');
  phs.forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (key) el.placeholder = t(key);
  });
  const titles = document.querySelectorAll('[data-i18n-title]');
  titles.forEach(el => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
  document.title = t('app.title');
}

// Load saved language
(function initLang() {
  try {
    const saved = localStorage.getItem('commanderbot_lang');
    if (saved && LANG[saved]) currentLang = saved;
  } catch {}
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'es';
  document.addEventListener('DOMContentLoaded', () => {
    document.title = t('app.title');
  });
})();
